DROP DATABASE IF EXISTS resolveaidb;
CREATE DATABASE resolveaidb;
USE resolveaidb;

CREATE TABLE SETOR (
    idSETOR INT NOT NULL AUTO_INCREMENT,
    nome VARCHAR(45) NOT NULL,
    descricao VARCHAR(500),
    PRIMARY KEY (idSETOR)
);

CREATE TABLE USUARIO (
    idUSUARIO INT NOT NULL AUTO_INCREMENT,
    nome VARCHAR(60) NOT NULL,
    data_cadastro DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cpf VARCHAR(14) NOT NULL UNIQUE,
    telefone VARCHAR(20),
    email VARCHAR(100) NOT NULL UNIQUE,
    senha VARCHAR(255) NOT NULL,
    tipo_usuario VARCHAR(20) NOT NULL,
    SETOR_idSETOR INT NOT NULL,
    PRIMARY KEY (idUSUARIO),
    FOREIGN KEY (SETOR_idSETOR) REFERENCES SETOR (idSETOR)
);

CREATE TABLE LOCALIZACAO (
    idLOCALIZACAO INT NOT NULL AUTO_INCREMENT,
    nome_localizacao VARCHAR(50) NOT NULL,
    PRIMARY KEY (idLOCALIZACAO)
);

CREATE TABLE PATRIMONIO (
    idPATRIMONIO INT NOT NULL AUTO_INCREMENT,
    nome VARCHAR(60) NOT NULL,
    valor DECIMAL(12,2),
    descricao VARCHAR(500),
    estado_conservacao VARCHAR(20),
    data_compra DATE,
    LOCALIZACAO_idLOCALIZACAO INT NOT NULL,
    PRIMARY KEY (idPATRIMONIO),
    UNIQUE (idPATRIMONIO, LOCALIZACAO_idLOCALIZACAO),
    FOREIGN KEY (LOCALIZACAO_idLOCALIZACAO) REFERENCES LOCALIZACAO (idLOCALIZACAO)
);

CREATE TABLE MATERIAL (
    idMATERIAL INT NOT NULL AUTO_INCREMENT,
    nome_material VARCHAR(60) NOT NULL,
    quantidade_estoque DECIMAL(10,2) NOT NULL,
    data_compra DATE,
    valor DECIMAL(12,2) NOT NULL,
    PRIMARY KEY (idMATERIAL),
    CHECK (quantidade_estoque >= 0),
    CHECK (valor >= 0)
);

CREATE TABLE ORDEMSERVICO (
    idORDEMSERVICO INT NOT NULL AUTO_INCREMENT,
    titulo_os VARCHAR(100) NOT NULL,
    observacao VARCHAR(500),
    data_abertura DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_inicio DATETIME,
    data_fim DATETIME,
    prazo_previsto DATE,
    prioridade VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    tipo_manutencao VARCHAR(20) NOT NULL,
    recorrente TINYINT NOT NULL DEFAULT 0,
    intervalo_dias INT,
    duracao_dias INT,
    proxima_data DATE,
    USUARIO_idSolicitante INT NOT NULL,
    USUARIO_idExecutor INT,
    SETOR_idSETOR INT NOT NULL,
    LOCALIZACAO_idLOCALIZACAO INT NOT NULL,
    PATRIMONIO_idPATRIMONIO INT,
    PRIMARY KEY (idORDEMSERVICO),
    CHECK (data_fim IS NULL OR data_inicio IS NULL OR data_fim >= data_inicio),
    CHECK (recorrente = 1 OR (intervalo_dias IS NULL AND proxima_data IS NULL)),
    FOREIGN KEY (USUARIO_idSolicitante) REFERENCES USUARIO (idUSUARIO),
    FOREIGN KEY (USUARIO_idExecutor) REFERENCES USUARIO (idUSUARIO),
    FOREIGN KEY (SETOR_idSETOR) REFERENCES SETOR (idSETOR),
    FOREIGN KEY (LOCALIZACAO_idLOCALIZACAO) REFERENCES LOCALIZACAO (idLOCALIZACAO),
    FOREIGN KEY (PATRIMONIO_idPATRIMONIO, LOCALIZACAO_idLOCALIZACAO)
        REFERENCES PATRIMONIO (idPATRIMONIO, LOCALIZACAO_idLOCALIZACAO)
);



CREATE TABLE ORDEMSERVICO_has_MATERIAL (
    idITEM INT NOT NULL AUTO_INCREMENT,
    ORDEMSERVICO_idORDEMSERVICO INT NOT NULL,
    MATERIAL_idMATERIAL INT NOT NULL,
    quantidade_usada DECIMAL(10,2) NOT NULL,
    valor_unitario DECIMAL(12,2) NOT NULL,

    PRIMARY KEY (idITEM),
    CHECK (quantidade_usada > 0),
    CHECK (valor_unitario >= 0),
    FOREIGN KEY (ORDEMSERVICO_idORDEMSERVICO) REFERENCES ORDEMSERVICO (idORDEMSERVICO),
    FOREIGN KEY (MATERIAL_idMATERIAL) REFERENCES MATERIAL (idMATERIAL)
);